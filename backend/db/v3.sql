CREATE TABLE IF NOT EXISTS datasets(
 id TEXT PRIMARY KEY, suite TEXT NOT NULL, seed INTEGER NOT NULL, manifest TEXT NOT NULL,
 digest TEXT NOT NULL, created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cases(
 id TEXT PRIMARY KEY, dataset TEXT NOT NULL REFERENCES datasets(id), position INTEGER NOT NULL,
 pair TEXT NOT NULL, layout INTEGER NOT NULL, kind TEXT NOT NULL, difficulty TEXT NOT NULL,
 question TEXT NOT NULL, options TEXT NOT NULL, answer TEXT NOT NULL, evidence TEXT NOT NULL,
 png BLOB NOT NULL, digest TEXT NOT NULL, UNIQUE(dataset,position));
CREATE INDEX IF NOT EXISTS case_dataset ON cases(dataset,position);
CREATE TABLE IF NOT EXISTS reviews(id TEXT PRIMARY KEY,dataset TEXT NOT NULL UNIQUE REFERENCES datasets(id),maps TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sheets(review TEXT NOT NULL REFERENCES reviews(id),reviewer TEXT NOT NULL,
 raw TEXT NOT NULL,digest TEXT NOT NULL,created TEXT DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(review,reviewer));
CREATE TABLE IF NOT EXISTS decisions(review TEXT PRIMARY KEY REFERENCES reviews(id),notes TEXT NOT NULL,accepted INTEGER NOT NULL,created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS calibrations(id TEXT PRIMARY KEY,task TEXT NOT NULL,record TEXT NOT NULL,created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS captures(cal TEXT REFERENCES calibrations(id),stage TEXT,observed TEXT NOT NULL,observer TEXT NOT NULL,
 png BLOB NOT NULL,digest TEXT NOT NULL UNIQUE,original BLOB NOT NULL,original_digest TEXT NOT NULL,created TEXT DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(cal,stage));
CREATE TABLE IF NOT EXISTS runs(id TEXT PRIMARY KEY,dataset TEXT NOT NULL REFERENCES datasets(id),provider TEXT NOT NULL,model TEXT NOT NULL,mode TEXT NOT NULL,
 settings TEXT NOT NULL,source TEXT NOT NULL,created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS calls(run TEXT REFERENCES runs(id),task TEXT REFERENCES cases(id),status TEXT NOT NULL,raw TEXT,parsed TEXT,
 metadata TEXT NOT NULL,started REAL NOT NULL,PRIMARY KEY(run,task));
CREATE TABLE IF NOT EXISTS evaluations(task TEXT,session TEXT,model TEXT,status TEXT,raw TEXT,metadata TEXT,
 created TEXT DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(task,session,model));
CREATE TABLE IF NOT EXISTS events(id INTEGER PRIMARY KEY,action TEXT,object_id TEXT,digest TEXT,created TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS quotas(bucket TEXT PRIMARY KEY,count INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,expires REAL NOT NULL);
CREATE TABLE IF NOT EXISTS approved_media(digest TEXT PRIMARY KEY REFERENCES captures(digest),created TEXT DEFAULT CURRENT_TIMESTAMP);
